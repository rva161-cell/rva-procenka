def fmt_price(p) -> str:
    try:
        return f"{float(p):,.2f}".replace(",", " ").replace(".00", "") + " ₽"
    except (TypeError, ValueError):
        return "? ₽"


def card_text(c: dict, attrs_line: str | None) -> str:
    title = " — ".join(x for x in (c.get("brand"), c.get("name")) if x) or "неизвестный товар"
    lines = [f"🔍 Похоже, это: {title}"]
    if c.get("brand"):
        lines.append(f"🏷 Бренд: {c['brand']}")
    if c.get("verified"):
        sup = f" ({', '.join(c['suppliers'])})" if c.get("suppliers") else ""
        lines.append(f"🔢 Артикул: {c['code']} ✅ подтверждён по базе поставщиков{sup}")
    else:
        lines.append(f"🔢 Артикул: {c['code']} ⚠️ не подтверждён по базам — предположение распознавания")
    if attrs_line:
        lines.append(attrs_line)
    lines += ["", "Это верная деталь?"]
    return "\n".join(lines)


def attrs_line_of(v: dict) -> str | None:
    parts = [f"{k}: {val}" for k, val in list(v.get("attributes", {}).items())[:6]]
    return "📋 " + "; ".join(parts) if parts else None


def offers_text(rows: list[dict], source: str, c: dict,
                cfg: dict, total: int | None = None) -> str:
    """Топ предложений. rows уже обрезаны правилами уровня (apply_guest_rules)."""
    lines = [f"💰 Проценка: {c.get('brand') or ''} {c['code']} (точные, без аналогов)", ""]
    for i, row in enumerate(rows[:3], 1):
        bits = [f"{i}. {fmt_price(row.get('price'))}"]
        if row.get("term") is not None:
            bits.append(f"{row['term']} дн")
        if row.get("amount"):
            bits.append(f"{row['amount']} шт")
        if row.get("warehouse"):
            bits.append(str(row["warehouse"])[:40])
        lines.append(" — ".join(b for b in bits if b))
        if row.get("name"):
            lines.append(f"    {str(row['name'])[:90]}")
    lines.append("")
    if total and total > min(len(rows), 3):
        lines.append(f"Показаны первые {min(len(rows), 3)} из {total} доступных вам.")
    url = (cfg.get("site") or {}).get("procenka_public_url") or (cfg.get("procenka") or {}).get("url", "")
    lines.append(f"Источник: {source}. Полная проценка с аналогами: {url}")
    return "\n".join(lines)


def level_status_text(info: dict) -> str:
    """Строка «Ваш уровень…» для /start и после привязки аккаунта."""
    lvl = info.get("level") or LEVEL_GUEST
    lines = [f"👤 Ваш уровень: {LEVEL_NAMES.get(lvl, lvl)}"]
    if info.get("login"):
        lines[0] += f" ({info['login']})"
    discount = int(info.get("discount") or 0)
    if discount:
        lines.append(f"🎁 Ваша скидка за приглашения: {discount}%")
    elif lvl < LEVEL_CLOSE:
        lines.append("👥 За каждых 10 приглашённых друзей — скидка 2% (максимум 10%).")
    if lvl >= LEVEL_CLOSE:
        lines.append("Доступно всё, включая будущие функции.")
    elif lvl >= LEVEL_SUPPLIER:
        lines.append("Доступны поиск по фото и проценка по вашим поставщикам.")
    elif lvl >= LEVEL_REG:
        lines.append("Доступны комментарии и заказ аудита/консультации.")
    else:
        lines.append("Доступен поиск по артикулу (первые предложения, без поставщиков).")
    if info.get("offline"):
        lines.append("⚠️ Сервер учётных записей недоступен — работаю в гостевом режиме.")
    elif lvl < LEVEL_SUPPLIER:
        lines.append("🔍 Поиск по фото и цены поставщиков откроются на уровне 3: "
                     "зарегистрируйтесь на странице проценки и нажмите 📱 «Привязать аккаунт» здесь.")
    return "\n".join(lines)


