def news_feed_text(items: list[dict]) -> str:
    """Лента новостей (HTML). items — из core.news.fetch_news()."""
    if not items:
        return NEWS_EMPTY
    lines = ["📰 <b>Лента новостей</b>", ""]
    for n in items:
        date = str(n.get("date") or "").strip()
        title = str(n.get("title") or "").strip()
        body = str(n.get("text") or "").strip()
        if date:
            lines.append(f"🗓 {date}")
        if title:
            lines.append(f"<b>{title}</b>")
        if body:
            lines.append(body)
        lines.append("")
    return "\n".join(lines).strip()

